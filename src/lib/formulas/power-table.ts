export const POWER_TABLE_MAX = POWER_TABLE.length - 1;

/** `sum` is a 2d6 result of 3-12 — a natural 2 does not belong here, see the module doc. */
export function powerTableRoll(power: number, sum: number): number {
  if (sum < 3 || sum > 12) throw new RangeError(`powerTableRoll: sum must be 3-12, got ${sum}`);
  const row = POWER_TABLE[Math.max(0, Math.min(POWER_TABLE_MAX, Math.round(power)))];
  return row[sum - 3];
}
