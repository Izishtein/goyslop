// Reads the Power of every damaging or healing spell out of the spell effect texts the reference
// already carries (src/i18n/locales/en.json, reference.spellEffect — the book's own wording) and
// writes src/data/spell-power.ts. A Fellow Action Table row for a spell needs this number
// ("Power 10+5"), and the spell catalogue itself holds no effect data.
//
// Run from the repository root:  node scripts/extract-spell-power.mjs
import fs from 'node:fs';

const effects = JSON.parse(fs.readFileSync('src/i18n/locales/en.json', 'utf8')).reference.spellEffect;
const rows = [];
for (const [id, text] of Object.entries(effects)) {
  // The base effect only — "Enhancement Effect" paragraphs describe paid upgrades.
  const base = text.split(/Enhancement Effect/i)[0];
  const match = /Power\s*(\d+)\s*\+\s*Magic Power/i.exec(base);
  if (!match) continue;
  // The sentence that holds the Power: a healing spell says "heals / restores / recovers" before (or
  // instead of) any "damage", a damaging one the other way round ("Heals Power 10 + Magic Power damage").
  const sentences = base.split(/(?<=[.!?])s+/);
  const sentence = sentences.find((entry) => entry.includes(match[0])) ?? '';
  const first = /healw*|restorw*|recoverw*|damage/i.exec(sentence)?.[0].toLowerCase();
  const heals = first !== undefined && first !== 'damage';
  rows.push({ id, power: Number(match[1]), kind: heals ? 'heal' : 'damage' });
}
rows.sort((a, b) => a.id.localeCompare(b.id));

const body = rows.map((row) => `  '${row.id}': { power: ${row.power}, kind: '${row.kind}' },`).join('\n');
fs.writeFileSync(
  'src/data/spell-power.ts',
  `// Generated by scripts/extract-spell-power.mjs from the spell effect texts — do not edit by hand.
// Spells whose base effect reads "Power N + Magic Power": the Power of the damage dealt or HP healed.

export interface SpellPower {
  power: number;
  kind: 'damage' | 'heal';
}

export const SPELL_POWER: Record<string, SpellPower> = {
${body}
};

export function getSpellPower(spellId: string): SpellPower | undefined {
  return SPELL_POWER[spellId];
}
`,
);
console.log(`${rows.length} spells (${rows.filter((r) => r.kind === 'heal').length} healing) written`);
