// usage: node scripts/vendor-game-icons.mjs
// Reads scripts/game-icons.spec.json ({ "semantic.key": "author/icon-name" }), fetches each icon from the game-icons/icons
// repository (CC BY 3.0, https://game-icons.net) and writes src/data/game-icons.generated.ts with just the path data of the
// icons the app uses and the folder (author) each came from, which the credits list needs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(fs.readFileSync(path.join(here, 'game-icons.spec.json'), 'utf8'));
const sources = [...new Set(Object.values(spec))].sort();
const fetched = {};
for (const source of sources) {
  const response = await fetch(`https://raw.githubusercontent.com/game-icons/icons/master/${source}.svg`);
  if (!response.ok) throw new Error(`${source}: ${response.status}`);
  const svg = await response.text();
  // the file is a black 512x512 square with the white glyph on top: keep the glyph's paths only
  const paths = [...svg.matchAll(/<path\b([^>]*)\/>/g)].map((match) => match[1]).filter((attrs) => !/d="M0 0h512v512H0z"/.test(attrs)).map((attrs) => /\bd="([^"]+)"/.exec(attrs)?.[1]).filter(Boolean);
  if (paths.length === 0) throw new Error(`${source}: no glyph path`);
  fetched[source] = paths.join(' ');
}
const lines = [
  '// Generated by scripts/vendor-game-icons.mjs from scripts/game-icons.spec.json - do not edit by hand.',
  '// Icons from https://game-icons.net, licensed CC BY 3.0 (the author is the folder of the game-icons/icons repository).',
  '',
  '/** Path data on a 512x512 canvas, by "author/name" in game-icons/icons. */',
  'export const ICON_PATHS: Record<string, string> = {',
  ...sources.map((source) => `  '${source}': ${JSON.stringify(fetched[source])},`),
  '};',
  '',
  '/** What the app calls each icon -> the icon it uses. */',
  'export const GAME_ICONS = {',
  ...Object.entries(spec).map(([key, source]) => `  '${key}': '${source}',`),
  '} as const;',
  '',
  'export type GameIconKey = keyof typeof GAME_ICONS;',
  '',
];
fs.writeFileSync(path.join(here, '..', 'src', 'data', 'game-icons.generated.ts'), lines.join('\n'));
console.log(`${Object.keys(spec).length} keys, ${sources.length} icons`);
